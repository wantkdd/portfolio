import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

// Inputs: original images from the supplied Figma file and the CAD research
// report (`<input>/<name>.png`), plus diagrams drawn for this site (scripts/diagrams).
const inputDirectory = process.argv[2] ?? "public/images";
const names = [
  "portrait",
  "whylog",
  "plog",
  "moa",
  "moamoa",
  "moamoa2",
  "leafly",
  "image-to-cad",
  "image-to-cad-2",
  "image-to-cad-3",
  "gotit",
  "sightline",
  "sightline-2",
  "sightline-3",
];
const diagrams = ["ax-frontier", "hsu-reserve", "ekec"];
const sources = [
  ...names.map((name) => [name, path.join(inputDirectory, `${name}.png`)]),
  ...diagrams.map((name) => [
    name,
    path.join("scripts/diagrams", `${name}.svg`),
  ]),
];
const dimensions = {};
await mkdir("public/images", { recursive: true });
for (const [name, source] of sources) {
  const width =
    name === "portrait" ? 320 : name.startsWith("moamoa") ? 640 : 1600;
  const result = await sharp(source, { density: 144 })
    .resize({ width, withoutEnlargement: true })
    .webp({ quality: 88, effort: 6 })
    .toFile(`public/images/${name}.webp`);
  dimensions[name] = { width: result.width, height: result.height };
  console.log(
    `${name}: ${result.width}×${result.height}, ${Math.round(result.size / 1024)} KB`,
  );
}
await writeFile(
  "src/data/image-dimensions.ts",
  `// Generated by scripts/optimize-assets.mjs; preserve original aspect ratios.\nexport const imageDimensions = ${JSON.stringify(dimensions, null, 2)} as const;\n`,
);
